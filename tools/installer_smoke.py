#!/usr/bin/env python3
"""installer_smoke.py -- prove the uninstaller removes its own files and nothing else (G36).

    python tools/installer_smoke.py
    python tools/installer_smoke.py --keep

The installer used to end with ``RMDir /r "$INSTDIR"``: whatever else lived in
the folder the user picked was deleted with the app, and the installer never
checked that the folder was the app's to write into.  ``tools/installer.nsi``
now lays down ``install-manifest.txt`` (generated by ``tools/make-installer.mjs``
from the payload walk) and removes only the files that list names, plus refuses a
folder that holds someone else's files.

This script compiles a tiny installer (a payload of two files, no signing and no
payload audit: ``--dev --no-audit``) and checks the four promises, on the real
Windows installer and the real uninstaller:

  install    a new folder gets the payload, the licence, the manifest, the
             uninstaller -- and an upgrade over the same folder succeeds;
  uninstall  the payload, the licence, the manifest and the uninstaller go;
             a stranger's file at the top and in a subdirectory stay, and the
             folders that still hold them stay;
  guard      installing into a folder that holds a stranger's file is refused
             (exit code 2, the NSIS abort code) and writes nothing;
  no marker  an uninstaller copied away from its install manifest deletes
             nothing (the copied file and the stranger's file survive).

``make test`` runs it; a machine without NSIS skips it with exit 0, the same way
the browser smokes skip without a browser.

Exit codes
    0   every promise held (or NSIS/makensis was not found)
    1   a promise broke
    2   a fixture could not be built
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "build" / "installer-smoke"
NODE = os.environ.get("NODE", "node")


def fail(message: str) -> None:
    print(f"installer-smoke: FAIL: {message}")
    sys.exit(1)


def skip(message: str) -> None:
    print(f"installer-smoke: skipped: {message}")
    sys.exit(0)


def run(cmd: list[str], timeout: int = 300) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, timeout=timeout)


def wait_until(predicate, seconds: float = 20.0) -> bool:
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if predicate():
            return True
        time.sleep(0.1)
    return predicate()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--keep", action="store_true", help="keep build/installer-smoke for inspection")
    args = parser.parse_args()

    if os.name != "nt":
        skip("the installer only exists on Windows")

    pkg = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    app_name = pkg.get("productName") or pkg["name"]
    app_exe = f"{app_name}.exe"

    if WORK.exists():
        shutil.rmtree(WORK)
    payload = WORK / "payload"
    (payload / "sub" / "deep").mkdir(parents=True)
    # The payload is never executed: the installer only packs and copies it.
    (payload / app_exe).write_bytes(b"MZ installer smoke payload\n")
    (payload / "sub" / "deep" / "data.txt").write_text("payload data\n", encoding="utf-8")

    setup = WORK / "setup.exe"
    print(f"installer-smoke: building {setup.name}")
    built = run([
        NODE, "tools/make-installer.mjs",
        "--payload", str(payload),
        "--out", str(setup),
        "--no-sign", "--dev", "--no-audit",
    ])
    if built.returncode != 0:
        text = built.stdout + built.stderr
        if "makensis.exe not found" in text:
            skip("makensis.exe not found (electron-builder's cache is searched too)")
        fail(f"make-installer.mjs exited {built.returncode}:\n{text[-4000:]}")
    if not setup.exists():
        fail(f"make-installer.mjs did not write {setup}")

    def install(target: Path) -> int:
        done = subprocess.run([str(setup), "/S", f"/D={target}"], cwd=ROOT, timeout=180)
        return done.returncode

    def uninstall(target: Path) -> None:
        uninstaller = target / f"Uninstall {app_name}.exe"
        subprocess.run([str(uninstaller), "/S"], cwd=ROOT, timeout=180)
        # The uninstaller stub hands off to a copy of itself and returns at once.
        wait_until(lambda: not (target / app_exe).exists())

    # ------------------------------------------------------------------
    # install, then upgrade over the same folder
    # ------------------------------------------------------------------
    installed = WORK / "install"
    code = install(installed)
    if code != 0:
        fail(f"install into a new folder exited {code}")
    for rel in ["", "sub/deep/data.txt", "EULA.txt", "install-manifest.txt", f"Uninstall {app_name}.exe"]:
        path = installed / app_exe if rel == "" else installed / rel
        if not path.exists():
            fail(f"install left no {rel or app_exe}")
    manifest = (installed / "install-manifest.txt").read_text(encoding="utf-8", errors="replace")
    if app_exe not in manifest:
        fail("install-manifest.txt does not list the payload's own exe")
    code = install(installed)
    if code != 0:
        fail(f"upgrade over the same folder exited {code}")

    # ------------------------------------------------------------------
    # a stranger's files are not the uninstaller's to delete
    # ------------------------------------------------------------------
    # Keep a copy of the uninstaller before it deletes itself: the last check
    # below needs one away from its manifest.
    shutil.copy2(installed / f"Uninstall {app_name}.exe", WORK / "uninstaller.exe")
    (installed / "user-note.txt").write_text("mine\n", encoding="utf-8")
    (installed / "mine").mkdir()
    (installed / "mine" / "keep.txt").write_text("keep\n", encoding="utf-8")
    uninstall(installed)
    if not wait_until(lambda: not (installed / "install-manifest.txt").exists()):
        fail("uninstall did not remove install-manifest.txt")
    survivors = sorted(str(p.relative_to(installed)).replace("\\", "/")
                       for p in installed.rglob("*") if p.is_file())
    if survivors != ["mine/keep.txt", "user-note.txt"]:
        fail(f"uninstall left {survivors}, expected only the two stranger files")

    # ------------------------------------------------------------------
    # the installer refuses a folder holding a stranger's file
    # ------------------------------------------------------------------
    guarded = WORK / "guarded"
    guarded.mkdir()
    (guarded / "stranger.txt").write_text("not ours\n", encoding="utf-8")
    code = install(guarded)
    if code != 2:
        fail(f"install into a folder holding a stranger's file exited {code}, expected 2 (Abort)")
    if (guarded / app_exe).exists():
        fail("refused install wrote the app anyway")

    # ------------------------------------------------------------------
    # an uninstaller without its manifest deletes nothing
    # ------------------------------------------------------------------
    copied = WORK / "copied"
    copied.mkdir()
    (copied / "stranger.txt").write_text("not ours\n", encoding="utf-8")
    shutil.copy2(WORK / "uninstaller.exe", copied / "u.exe")
    subprocess.run([str(copied / "u.exe"), "/S"], cwd=ROOT, timeout=180)
    time.sleep(1.0)
    names = sorted(p.name for p in copied.iterdir())
    if names != ["stranger.txt", "u.exe"]:
        fail(f"a manifest-less uninstaller left {names}, expected the file and itself")

    if not args.keep:
        shutil.rmtree(WORK)
    print("installer-smoke: ok -- 4 promises held (install+upgrade, scoped uninstall, "
          "foreign-folder guard, no-manifest no-delete)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
